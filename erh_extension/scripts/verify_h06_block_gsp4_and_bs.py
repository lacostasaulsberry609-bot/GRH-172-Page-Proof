def compute_HM_real(f, eta_fn, M):
    """
    Exact rational norm-pushforward H_M(r) for real-valued character eta of period f (gcd(M, f) = 1):
      G_M(u1, u2) = (1/f^2) sum_{r1, r2=0}^{f-1} r1 r2 eta(u1 + r1*M, u2 + r2*M)
      H_M(r) = sum_{1 <= u1, u2 <= M, N(u1 + u2*eps_+) == r mod M} G_M(u1, u2).
    """
    assert math.gcd(f, M) == 1
    # Precompute S(a, b) = sum_{r1, r2=0}^{f-1} r1 r2 eta(a + r1*M, b + r2*M) for a, b mod f
    # Using x1 = a + r1*M mod f => r1 = ((x1 - a)*M^{-1} mod f)
    invM = pow(M, -1, f)
    # Table eta[x1][x2]
    E = [[eta_fn(x1, x2) for x2 in range(f)] for x1 in range(f)]
    # Check zero row and column sums
    for x1 in range(f):
        assert sum(E[x1]) == 0
    for x2 in range(f):
        assert sum(E[x1][x2] for x1 in range(f)) == 0
    # Compute S_mod_f[a][b] = sum_{x1, x2} ((x1-a)*invM mod f) * ((x2-b)*invM mod f) * E[x1][x2]
    # Fast O(f^3): first sum over x2 for each (x1, b)
    T = [[0] * f for _ in range(f)]
    for x1 in range(f):
        rowE = E[x1]
        for b in range(f):
            s = 0
            for x2 in range(f):
                v = rowE[x2]
                if v:
                    s += (((x2 - b) * invM) % f) * v
            T[x1][b] = s
    S = [[0] * f for _ in range(f)]
    for a in range(f):
        for b in range(f):
            s = 0
            for x1 in range(f):
                s += (((x1 - a) * invM) % f) * T[x1][b]
            S[a][b] = s
    # Sum over 1 <= u1, u2 <= M grouped by norm N(u1, u2) = u1^2 + 3*u1*u2 + u2^2 mod M
    H_num = defaultdict(int)
    for u1 in range(1, M + 1):
        a = u1 % f
        Sa = S[a]
        for u2 in range(1, M + 1):
            nm = (u1 * u1 + 3 * u1 * u2 + u2 * u2) % M
            if math.gcd(nm, M) == 1:
                H_num[nm] += Sa[u2 % f]
    f2 = f * f
    H = {}
    for r, val in H_num.items():
        H[r] = Fraction(val, f2)
    return H


