def poly2d_mul(A, B, max_a, max_b):
    C = [[0] * (max_b + 1) for _ in range(max_a + 1)]
    for i in range(max_a + 1):
        Ai = A[i]
        for j in range(max_b + 1):
            v = Ai[j]
            if v == 0:
                continue
            for p in range(max_a + 1 - i):
                Bp = B[p]
                Cp = C[i + p]
                for q in range(max_b + 1 - j):
                    if Bp[q]:
                        Cp[j + q] += v * Bp[q]
    return C

def series_inv_1_minus(dx, dy, max_a, max_b):
    """Power series of 1 / (1 - x^dx y^dy) truncated to [0..max_a] x [0..max_b]."""
    S = [[0] * (max_b + 1) for _ in range(max_a + 1)]
    k = 0
    while k * dx <= max_a and k * dy <= max_b:
        S[k * dx][k * dy] = 1
        k += 1
    return S

def poly_1_minus(dx, dy, max_a, max_b):
    P = [[0] * (max_b + 1) for _ in range(max_a + 1)]
    P[0][0] = 1
    if dx <= max_a and dy <= max_b:
        P[dx][dy] -= 1
    return P

def eval_multirees_gf(num_factors, den_factors, max_a=24, max_b=24):
    """Exact integer coefficients [x^a y^b] of prod(1 - x^dx y^dy) / prod(1 - x^dx y^dy)."""
    S = [[0] * (max_b + 1) for _ in range(max_a + 1)]
    S[0][0] = 1
    for (dx, dy, mult) in num_factors:
        F = poly_1_minus(dx, dy, max_a, max_b)
        for _ in range(mult):
            S = poly2d_mul(S, F, max_a, max_b)
    for (dx, dy, mult) in den_factors:
        F = series_inv_1_minus(dx, dy, max_a, max_b)
        for _ in range(mult):
            S = poly2d_mul(S, F, max_a, max_b)
    return S

