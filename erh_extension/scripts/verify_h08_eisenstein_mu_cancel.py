def module_1_residual_spectrum_dichotomy():
    print("=" * 72)
    print("[Module 1] Residual Spectrum Dichotomy & Self-Twist Classification on L'^+")
    print("=" * 72)

    primes = [p for p in range(5, 48) if isprime(p)]
    checked_pairs = 0
    for ell in primes:
        # On L'^+ = (L(zeta_ell))^+, omega_ell|_{G_{L'^+}} = theta' (order 2).
        # For inert q: N(q) = -1 (mod ell), so 1 + N(q) = 0 (mod ell).
        assert (1 + (-1)) % ell == 0
        # For split q: N(q) = +1 (mod ell), so 1 + N(q) = 2 != 0 (mod ell) since ell >= 5.
        assert (1 + 1) % ell != 0

        # Test over F_{ell^2} or roots of unity of order d_psi dividing ell^2 - 1 (prime to ell)
        # Check algebraic criterion for bar{a}_q(F_2) = theta'(q)*z + z^{-1}
        z = Symbol("z")
        a_inert = -z + 1 / z  # = (1 - z^2)/z
        a_split = z + 1 / z   # = (1 + z^2)/z
        assert simplify(a_inert - (1 - z**2) / z) == 0
        assert simplify(a_split - (1 + z**2) / z) == 0

        # Regime I: z^2 != 1 => a_inert != 0 while T_q|_E = (1 + Nq) = 0 (mod ell)
        # Regime II: z^2 == 1 => a_inert == 0, a_split == +-2 != 0 (mod ell)
        for z_val in [1, ell - 1]:
            assert ((-z_val + pow(z_val, -1, ell)) % ell) == 0
            assert ((z_val + pow(z_val, -1, ell)) % ell) in (2, ell - 2)
            assert ((z_val + pow(z_val, -1, ell)) % ell) != 0

        # Check all non-quadratic elements z in F_ell^* (when ell >= 5, |F_ell^*| >= 4)
        non_quad = [x for x in range(1, ell) if (x * x) % ell != 1]
        assert len(non_quad) == ell - 3 >= 2
        for x in non_quad:
            inv_x = pow(x, -1, ell)
            assert ((-x + inv_x) % ell) != 0, f"Inert eigenvalue vanished for non-quadratic x={x} mod {ell}"
            checked_pairs += 1

    # Self-twist classification for bar{rho}_{F_2}^{ss} = (theta' * psi) (+) psi^{-1}:
    # (theta'*psi*eta, psi^{-1}*eta) == {theta'*psi, psi^{-1}} as multisets:
    # Diagonal match: eta = 1
    # Swap match: eta = theta' * psi^{-2} AND eta = theta'^{-1} * psi^{2} => psi^4 = 1 (since theta'^2 = 1)
    # Test finite cyclic groups C_m for m = 1..24
    for m in range(1, 25):
        # Test whether the subset S = {(t, g) in {+1,-1} x C_m : t*zeta^g + zeta^{-g} != 0}
        # generates {+1,-1} x C_m (here t = theta'(q), g = bar{psi}(q)).
        # Using exact roots of unity in C via cyclotomic check:
        # t*z + z^{-1} == 0 <=> z^2 == -t
        # For t = +1 (split): vanishes iff z^2 = -1 (order 4 elements)
        # For t = -1 (inert): vanishes iff z^2 = +1 (order 1 or 2 elements)
        # Check subgroup generated by non-vanishing pairs in Z/2Z x Z/mZ:
        G_elems = [(t, g) for t in (0, 1) for g in range(m)]  # t=0 split (+1), t=1 inert (-1)
        non_vanishing = []
        for t, g in G_elems:
            if t == 0:  # split: z^2 = -1 iff 4*g == 0 mod m and 2*g != 0 mod m (i.e. 2*g == m/2 mod m)
                vanishes = (m % 4 == 0) and ((2 * g) % m == m // 2)
            else:       # inert: z^2 = +1 iff 2*g == 0 mod m
                vanishes = ((2 * g) % m == 0)
            if not vanishes:
                non_vanishing.append((t, g))

        # Compute subgroup generated by non_vanishing in Z/2Z x Z/mZ
        sub = {(0, 0)}
        changed = True
        while changed:
            changed = False
            new_elems = set(sub)
            for a1, b1 in list(sub):
                for a2, b2 in non_vanishing:
                    elem = ((a1 + a2) % 2, (b1 + b2) % m)
                    if elem not in new_elems:
                        new_elems.add(elem)
                        changed = True
            sub = new_elems

        if m in (1, 2, 4):
            # Exactly index 2 subgroup ker(eta), where eta = theta' * psi^{-2}
            assert len(sub) == len(G_elems) // 2, f"Expected index 2 for m={m}, got {len(sub)}/{len(G_elems)}"
            # Check sub == ker(eta): eta(t, g) = (-1)^t * (zeta_m)^{-2g} == 1
            for t, g in G_elems:
                in_ker = (t == 0 and (2 * g) % m == 0) or (
                    t == 1 and m % 4 == 0 and (2 * g) % m == m // 2
                )
                assert ((t, g) in sub) == in_ker
        else:
            # For all m not dividing 4, non-vanishing primes generate ALL of Z/2Z x Z/mZ!
            assert len(sub) == len(G_elems), f"Expected full group for m={m}, got {len(sub)}/{len(G_elems)}"

    print(f"  [PASS] Verified {len(primes)} primes (ell in [5..47]), {checked_pairs} non-quadratic inert checks.")
    print("  [PASS] Verified exact self-twist dichotomy on Z/2Z x C_m (m=1..24):")
    print("         - m | 4 (ord(psi) in {1,2,4}): non-vanishing primes generate index-2 subgroup ker(theta'*psi^{-2});")
    print("         - m not| 4: non-vanishing primes generate the ENTIRE narrow class group.")


def module_2_brandt_graph_and_gross_matrices():
    print("\n" + "=" * 72)
    print("[Module 2] Definite Quaternion Eisenstein Subtraction, Bipartite Lemma & Gross Matrices")
    print("=" * 72)

    # 2.1 Symbolic 2x2 Gross-point matrix identities
    a, b, w, u0, z = symbols("a b w u0 z")
    # Standard Gross-point matrix g_n = [[w^n, 1], [0, 1]] and check-varsigma = [[1, w^{-n}], [0, 1]]
    wn, wn_m1, wj = symbols("wn wn_m1 wj")  # wn = w^n, wn_m1 = w^{n-1}, wj = w^j

    # Optimal embedding check for g_n = [[wn, 1], [0, 1]]:
    g_n = Matrix([[wn, 1], [0, 1]])
    diag_ab = Matrix([[a, 0], [0, b]])
    conj_gn = simplify(g_n.inv() * diag_ab * g_n)
    assert conj_gn == Matrix([[a, (a - b) / wn], [0, b]])

    # Optimal embedding check for check_s_n = [[1, 1/wn], [0, 1]]:
    cs_n = Matrix([[1, 1 / wn], [0, 1]])
    conj_csn = simplify(cs_n.inv() * diag_ab * cs_n)
    assert conj_csn == Matrix([[a, (a - b) / wn], [0, b]])

    # U_{v'_0} norm-compatibility identity for g_n = [[w^n, 1], [0, 1]]:
    # [[u0*(1 + w^{n-1}*z), 0], [0, 1]] * [[w^n, 1], [0, 1]]
    # == [[u0*w^{n-1}, u0], [0, 1]] * [[w, z], [0, 1]] * [[1 + w^{n-1}*z, 0], [0, 1]]
    lhs_U = Matrix([[u0 * (1 + wn_m1 * z), 0], [0, 1]]) * Matrix([[w * wn_m1, 1], [0, 1]])
    rhs_U = (
        Matrix([[u0 * wn_m1, u0], [0, 1]])
        * Matrix([[w, z], [0, 1]])
        * Matrix([[1 + wn_m1 * z, 0], [0, 1]])
    )
    assert simplify(lhs_U - rhs_U) == sp.zeros(2, 2)

    # Exact shift identity for check_s_n:
    # [[wj, 0], [0, 1]] * [[1, 1/(wj * w_nmj)], [0, 1]] == [[1, 1/w_nmj], [0, 1]] * [[wj, 0], [0, 1]]
    w_nmj = Symbol("w_nmj")
    lhs_shift = Matrix([[wj, 0], [0, 1]]) * Matrix([[1, 1 / (wj * w_nmj)], [0, 1]])
    rhs_shift = Matrix([[1, 1 / w_nmj], [0, 1]]) * Matrix([[wj, 0], [0, 1]])
    assert simplify(lhs_shift - rhs_shift) == sp.zeros(2, 2)

    # Exact relation g_n = [[w^n, 0], [0, 1]] * check_s_n:
    assert simplify(Matrix([[wn, 0], [0, 1]]) * cs_n - g_n) == sp.zeros(2, 2)
    print("  [PASS] All 5 symbolic 2x2 Gross-point & U_{v'_0}-compatibility matrix identities verified.")

    # 2.2 Explicit finite Brandt-graph toy model of Eisenstein congruence depth m >= 1
    # Take ell = 5, narrow class group Cl^+ = Z/2Z = {0 (split), 1 (inert)}.
    # Fiber X^{[0]} has 3 vertices with stabilizer weights w_x = (1, 1, 3) => mass = 1 + 1 + 1/3?
    # Better: weights w_x = (1, 2, 3, 6) => sum w_x^{-1} = 1 + 1/2 + 1/3 + 1/6 = 2.
    # For an ell=5 Eisenstein congruence of depth m=2 (mod 25), choose mass = 25/6:
    # e.g., 5 vertices on each fiber with w_x^{-1} = (1/6, 1, 1, 1, 1) => sum = 25/6 = 5^2 / 6!
    ell = 5
    inv_w = [Rational(1, 6), Rational(1, 1), Rational(1, 1), Rational(1, 1), Rational(1, 1)]
    mass = sum(inv_w)
    assert mass == Rational(25, 6)  # v_5(mass) = 2!

    # Construct a primitive integral function phi on X^{[0]} orthogonal to constant 1 (cuspidal!):
    # Require sum_x inv_w[x] * phi[x] == 0 AND phi[x] == 1 (mod 25) for all x!
    # Pick phi = [1 - 25*6, 1, 1, 1, 1]? Wait: sum = (1-150)/6 + 4 = -149/6 + 24/6 = -125/6 != 0!
    # Solve (1 + 25*k0)/6 + 4 = 0 => 1 + 25*k0 = -24 => 25*k0 = -25 => k0 = -1!
    # So phi_0 = [-24, 1, 1, 1, 1]!!
    phi_0 = [-24, 1, 1, 1, 1]
    assert sum(inv_w[i] * phi_0[i] for i in range(5)) == 0  # EXACT cuspidal orthogonality <phi, 1> = 0!
    assert all((v - 1) % (ell**2) == 0 for v in phi_0)       # Congruent to constant 1 mod 5^2 (m_Eis = 2)!
    assert any((v - 1) % (ell**3) != 0 for v in phi_0)       # Exact depth m_Eis = 2!

    # Subtract phi_Eis = [1, 1, 1, 1, 1] and divide by ell^2 = 25:
    phi_tilde = [(v - 1) // (ell**2) for v in phi_0]
    assert phi_tilde == [-1, 0, 0, 0, 0]
    assert len(set(v % ell for v in phi_tilde)) > 1  # Strictly non-constant mod 5!

    # 2.3 Verify Exact Inertia Annihilation Identity on finite group ring Z[G_n]
    # Model G_n = C_{h0} x K_n with h0 = 2, |K_n| = 5^2 = 25.
    # For ANY map x_n: G_n -> X^{[0]} and ANY phi = phi_Eis + ell^m * phi_tilde:
