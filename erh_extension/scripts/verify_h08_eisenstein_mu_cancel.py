            assert (Nq + 1) % ell == 0
            assert (NQ - 1) % ell == 0
            # Local cohomology of k(1) on G_{L'_Q}: since NQ == 1 mod ell, k(1) == k(trivial)
            # H^0 = k (dim 1), H^2 = H^0(k(1))^v = k (dim 1), chi = 0 => dim H^1 = 2
            # H^1_fin = k (dim 1), H^1_sing = k (dim 1).
